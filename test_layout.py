def _old_group_lines(lines, body):
    """Gap threshold as a multiple of line height. Welded paragraphs together."""
    blocks, current = [], []
    for line in lines:
        if not current:
            current = [line]
            continue
        previous = current[-1]
        gap = line.bbox[1] - previous.bbox[3]
        leading = max(previous.bbox[3] - previous.bbox[1], 1.0)
        style = (abs(line.size - previous.size) > 0.6
                 or line.bold != previous.bold)
        disjoint = (line.bbox[0] > previous.bbox[2] or line.bbox[2] < previous.bbox[0])
        if gap > leading * 1.6 or style or disjoint:
            blocks.append(current)
            current = [line]
        else:
            current.append(line)
    if current:
        blocks.append(current)
    return blocks


def _old_xy_cut(items, depth=0, max_depth=6):
    """Horizontal cut first. Interleaved every two-column page."""
    if len(items) <= 1 or depth >= max_depth:
        return list(items)
    for axis in (1, 0):
        lo_i, hi_i = (1, 3) if axis else (0, 2)
        ordered = sorted(items, key=lambda it: it[0][lo_i])
        reach = ordered[0][0][hi_i]
        best, best_gap = None, 0.0
        for i in range(1, len(ordered)):
            gap = ordered[i][0][lo_i] - reach
            if gap > best_gap:
                best_gap, best = gap, i
            reach = max(reach, ordered[i][0][hi_i])
        if best is not None and best_gap >= (4.0 if axis else layout.MIN_GUTTER_PT):
            return (_old_xy_cut(ordered[:best], depth + 1, max_depth)
                    + _old_xy_cut(ordered[best:], depth + 1, max_depth))
    return sorted(items, key=lambda it: (round(it[0][1], 1), it[0][0]))


def _old_column_bounds(lines, page_width):
    """"Empty for most of the page height." Called a table's gaps a gutter."""
    if len(lines) < 6:
        return [(0.0, page_width)]
    top = min(l.bbox[1] for l in lines)
    bottom = max(l.bbox[3] for l in lines)
    height = max(bottom - top, 1.0)
    step, n = 2.0, int(page_width / 2.0) + 1
    occupied = [0.0] * n
    for line in lines:
        lo, hi = int(line.bbox[0] / step), min(int(line.bbox[2] / step) + 1, n)
        for i in range(lo, hi):
            occupied[i] += line.bbox[3] - line.bbox[1]
    runs, start = [], None
    for i in range(n):
        if occupied[i] < height * 0.12:
            start = i if start is None else start
        else:
            if start is not None and (i - start) * step >= layout.MIN_GUTTER_PT:
                runs.append((start * step, i * step))
            start = None
    left = min(l.bbox[0] for l in lines)
    right = max(l.bbox[2] for l in lines)
    inner = [r for r in runs if r[0] > left + 1 and r[1] < right - 1]
    if not inner:
        return [(left, right)]
    bounds, cursor = [], left
    for lo, hi in inner:
        bounds.append((cursor, lo))
        cursor = hi
    bounds.append((cursor, right))
    return [b for b in bounds if b[1] - b[0] > 40] or [(left, right)]


REGRESSIONS = {
    "group_lines": (_old_group_lines,
                    ("paragraphs are not welded together",
                     "element types are right on every generated layout")),
    "xy_cut": (_old_xy_cut,
               ("a two-column page reads down one column then the other",)),
    "column_bounds": (_old_column_bounds,
                      ("a table's internal whitespace is not a column gutter",
                       "an unruled table is found, which find_tables cannot do")),
}


def verify_suite_is_not_decorative():
    by_name = dict(_results)
    lines, total_caught = [], 0
    for name, (old, targets) in REGRESSIONS.items():
        original = getattr(layout, name)
        setattr(layout, name, old)
        try:
            caught = 0
            for target in targets:
                try:
                    by_name[target]()
                except AssertionError:
                    caught += 1
        finally:
            setattr(layout, name, original)
        total_caught += caught
        lines.append(f"  pre-fix {name:<15} {caught}/{len(targets)} of its tests fail")
    return lines, total_caught


def main():
    failed = 0
    for name, fn in _results:
        try:
            fn()
            print(f"PASS  {name}")
        except AssertionError as exc:
            failed += 1
            print(f"FAIL  {name}\n      {exc}")
    print(f"\n{len(_results) - failed}/{len(_results)} passed")

    print("\nagainst the pre-fix implementations:")
    lines, caught = verify_suite_is_not_decorative()
    print("\n".join(lines))
    if caught < len(REGRESSIONS):
        print("the suite does not detect every bug it was written for")
        failed += 1
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
