@check("INVARIANT: every character on the page lands in some element")
def _():
    for kind in synth.LAYOUTS:
        elements, stats, _ = analyse((kind,))
        assert stats["coverage"] >= 0.999, \
            f"{kind}: coverage {stats['coverage']} -- text was dropped silently"


@check("INVARIANT: reading order is a total order with no gaps")
def _():
    elements, _, _ = analyse(("two-column",))
    orders = [e.order for e in elements if e.order]
    assert sorted(orders) == list(range(1, len(orders) + 1)), orders


@check("running heads stay out of the reading flow")
def _():
    elements, _, _ = analyse(("single",))
    running = [e for e in elements if e.type in ("header", "footer")]
    assert running, "no header/footer found at all"
    assert all(e.order == 0 for e in running)
    # ...and are still present, because dropping them would break coverage.
    assert any(e.text.strip() for e in running)


