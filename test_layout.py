@check("kendall tau punishes an interleaved order properly")
def _():
    assert metrics.kendall_tau([1, 2, 3, 4], [1, 2, 3, 4]) == 1.0
    assert metrics.kendall_tau([1, 2, 3, 4], [4, 3, 2, 1]) == -1.0
