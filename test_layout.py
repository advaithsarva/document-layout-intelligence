@check("a two-column page reads down one column then the other")
def _():
    # THE bug the XY-cut axis choice was fixed for. Two earlier versions failed
    # here: horizontal-first interleaved every page, and widest-gap-wins failed
    # whenever both columns broke a paragraph at the same height.
    for seed in (42, 43, 44, 45, 46, 47):
        elements, _, truth = analyse(("two-column",), seed=seed)
        score = metrics.score_page(truth, elements)
        assert score["order_tau"] > 0.99, \
            f"seed {seed}: tau {score['order_tau']}, columns interleaved"


@check("a full-width title above two columns needs no special case")
def _():
    elements, _, _ = analyse(("two-column",))
    ordered = flow(elements)
    assert ordered[0].type == "title", [e.type for e in ordered[:3]]
    # everything in column 0 comes before everything in column 1
    columns = [e.column for e in ordered[1:]]
    assert columns == sorted(columns), columns


@check("the naive top-to-bottom order is measurably wrong here")
def _():
    # If PyMuPDF's own sort=True scored as well as this project on the pages
    # this project exists for, the project would not be worth having.
    doc, truth = build(("two-column",), seed=43)
    try:
        page = doc[0]
        ours, _ = layout.analyse_page(page)
        naive = [_Simple(b[:4], i) for i, b in
                 enumerate(page.get_text("blocks", sort=True), start=1)
                 if str(b[4]).strip()]
    finally:
        doc.close()
    assert metrics.score_page(truth[0], ours)["order_tau"] > \
        metrics.score_page(truth[0], naive)["order_tau"] + 0.2


