"""One test per real bug, plus the invariant.

    python test_layout.py

No pytest, no network, no downloaded corpus -- the fixtures are generated by
`synth.py` in memory. Runs in about two seconds.

The last section, `verify_suite_is_not_decorative`, re-installs the *previous*
version of each fixed function and asserts the suite catches it. A test suite
that passes on the code it was written against proves nothing.
"""

import statistics
