@check("paragraphs are not welded together")
def _():
    # The gap threshold used to be `line_height * 1.6`, which demanded 17pt
    # when paragraphs sit 9pt apart. Recall was 0.53 and the output still
    # looked entirely plausible.
    elements, _, truth = analyse(("two-column",), seed=42)
    expected = len([t for t in truth if t.order])
    got = len(flow(elements))
    assert got >= expected * 0.85, f"{got} elements for {expected} in truth"


@check("the grouping threshold comes from the page, not a constant")
def _():
    tight = [layout.Line(f"line {i}", (54, 100 + i * 10, 300, 108 + i * 10),
                         9.5, False, "helv") for i in range(6)]
    assert len(layout.group_lines(tight, 9.5)) == 1
    spaced = [layout.Line(f"line {i}", (54, 100 + i * 10, 300, 108 + i * 10),
                          9.5, False, "helv") for i in range(3)]
    spaced += [layout.Line(f"line {i}", (54, 200 + i * 10, 300, 208 + i * 10),
                           9.5, False, "helv") for i in range(3)]
    assert len(layout.group_lines(spaced, 9.5)) == 2


