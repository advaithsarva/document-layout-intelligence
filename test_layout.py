@check("ground-truth boxes are ink, not the requested rectangle")
def _():
    # A one-word heading requested in a 504x19 box renders as ~51x13 of ink.
    # Labelling the request made every correct detection score IoU < 0.5, and
    # the evaluation reported 28 missed headings and 28 invented ones in the
    # same places.
    doc, truth = build(("single",))
    try:
        page = doc[0]
        heading = [t for t in truth[0] if t.type == "heading"][0]
        assert heading.bbox[2] - heading.bbox[0] < 300, heading.bbox
        found = [l for l in layout.page_lines(page)
                 if l.text.strip() == heading.text.strip()]
        assert found and metrics.iou(found[0].bbox, heading.bbox) > 0.7
    finally:
        doc.close()


