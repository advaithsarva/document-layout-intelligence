_results = []


def check(name):
    def wrap(fn):
        _results.append((name, fn))
        return fn
    return wrap


def build(layouts, seed=42):
    """A PDF in a temp file plus its ground truth, as (doc, truth)."""
    import os
    import tempfile
    handle, path = tempfile.mkstemp(suffix=".pdf")
    os.close(handle)
    truth = synth.build_document(path, layouts, seed=seed)
    doc = fitz.open(path)
    doc._temp_path = path
    return doc, truth


def analyse(layouts, seed=42, page=0):
    doc, truth = build(layouts, seed)
    try:
        elements, stats = layout.analyse_page(doc[page])
    finally:
        doc.close()
    return elements, stats, truth[page]


def flow(elements):
    return sorted((e for e in elements if e.order), key=lambda e: e.order)


